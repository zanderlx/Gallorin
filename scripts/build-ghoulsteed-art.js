import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';

const sources = [
  ['Base/Coat Bottom.svg', 'Base', 'coat bottom', 'Coat Bottom'],
  ['Base/Coat Top.svg', 'Base', 'coat top', 'Coat Top'],
  ['Base/Sock.svg', 'Base', 'sock', 'Sock'],
  ['Base/Hoof.svg', 'Base', 'hoof', 'Hoof'],
  ['Base/Eye.svg', 'Base', 'eye', 'Eye'],
  ['Base/Keratin.svg', 'Base', 'keratin', 'Keratin'],
  ['Mane/Tattered Mane/Hair.svg', 'Mane', 'Tattered Mane', 'Hair'],
  ['Mane/Tattered Mane/Pattern.svg', 'Mane', 'Tattered Mane', 'Pattern'],
  ['Pattern/Abyssal Rifts.svg', 'Pattern', 'Abyssal Rifts', 'Pattern'],
  ['Tail/Ancient Lupine Tail.svg', 'Tail', 'Ancient Lupine Tail', 'Hair']
];
const layers = await Promise.all(
  sources.map(async ([file, category, name, channel]) => ({
    category,
    name,
    channel,
    svg: await readFile(new URL('../docs/art/ghoulsteed/' + file, import.meta.url), 'utf8')
  }))
);
await writeFile(
  new URL('../public/trait-gallery-art.js', import.meta.url),
  await format(
    '// Generated by scripts/build-ghoulsteed-art.js from supplied Ghoulsteed SVGs.\nexport const ghoulsteedLayers = ' +
      JSON.stringify(layers) +
      ';\n',
    { parser: 'babel', singleQuote: true, printWidth: 120, trailingComma: 'none' }
  )
);
